# 1. Finds the directory where this script sits (assignment11/)
BASE_DIR = os.path.dirname(os.path.abspath(__file__))

# 2. Looks up one level (..), then into the root db/ folder
db_path = os.path.abspath(os.path.join(BASE_DIR, "..", "db", "lesson.db"))

# 3. Connect to the real database file directly
conn = sqlite3.connect(db_path)

query = """
SELECT 
    last_name, 
    SUM(price * quantity) AS revenue 
FROM employees e 
JOIN orders o ON e.employee_id = o.employee_id 
JOIN line_items l ON o.order_id = l.order_id 
JOIN products p ON l.product_id = p.product_id 
GROUP BY e.employee_id;
"""

employee_results = pd.read_sql_query(query, conn)
conn.close()


# Generate the bar chart using Pandas plotting functionality
employee_results.plot(
    x="last_name", 
    y="revenue", 
    kind="bar", 
    color="teal", 
    legend=False,
    title="Total Revenue Generated by Employee"
)

# Customize descriptive axis labels and spacing
plt.xlabel("Employee Last Name")
plt.ylabel("Total Revenue ($)")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()
